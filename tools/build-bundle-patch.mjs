// Regenerate bundle/cordis.patch.yml from the SHIPPED preset.
//
// WHY THIS EXISTS
// A loader patch replaces the whole `config` rather than deep-merging, so a preset
// override that drops a row silently removes a capability from every agent. This
// script builds the patch from the shipped file so that can never happen by hand,
// and `assert-preset-override.mjs` proves the result preserved every row.
//
// WHAT IT WRITES
//   1. Host-plane rows that stop the shipped PowerShell tool (two levers, because
//      neither alone was sufficient — see the generated comments).
//   2. The preset override, generated verbatim from the shipped preset with a single
//      `disabled: true` change.
//   3. The `insert` for this bundle's own row.
//
// Usage:
//   node tools/build-bundle-patch.mjs <shipped-preset.patch.yml> <out.patch.yml>
//
// The shipped preset lives at, in the running installation:
//   <app.asar>/dsh/node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml
// tools/extract-asar.mjs can materialize it if you only have the packaged desktop app.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , shippedPath, outPath] = process.argv;
if (shippedPath === undefined || outPath === undefined) {
  console.error('usage: build-bundle-patch.mjs <shipped-preset.patch.yml> <out.patch.yml>');
  process.exit(2);
}

const DISABLE = 'tool-pwsh';

/** Split the shipped preset into (indent, lines) and unwrap its `- insert:` block. */
function unwrapShippedPreset(text) {
  const rows = text
    .split(/\r?\n/)
    .filter((line) => !/^\s*#/.test(line) && line.trim() !== '');
  const at = rows.findIndex((line) => /^-\s+insert:\s*$/.test(line));
  if (at === -1) throw new Error('shipped preset: no top-level "- insert:" block');
  const body = rows.slice(at + 1);
  const strip = body[0].slice(0, body[0].indexOf('- id:'));
  if (strip.length === 0) throw new Error('preset row is already at top level; unexpected shape');
  return body.map((line) => (line.startsWith(strip) ? line.slice(strip.length) : line));
}

/**
 * Force `disabled: true` on the named plugin rows.
 * The shipped list already carries a `disabled: !!js process.platform ...` line on
 * tool-bash/tool-pwsh, so that line is REPLACED rather than a second `disabled:` key
 * appended (a duplicate key would be invalid YAML) — and simply skipping it would
 * leave the row live on the platform where its expression is falsy.
 */
function disableRows(rows, ids) {
  const out = [];
  const seen = [];
  let changed = 0;
  for (let i = 0; i < rows.length; i += 1) {
    const line = rows[i];
    const match = /^(\s*)-\s+id:\s*(\S+)\s*$/.exec(line);
    if (match) seen.push(match[2]);
    if (match === null || !ids.includes(match[2])) {
      out.push(line);
      continue;
    }
    const propIndent = `${match[1]}  `;
    let j = i + 1;
    const body = [];
    while (j < rows.length) {
      const next = rows[j];
      if (/^\s*-\s+id:/.test(next)) break;
      if (next.trim() !== '' && !next.startsWith(propIndent)) break;
      body.push(next);
      j += 1;
    }
    const at = body.findIndex((l) => /^\s*disabled:/.test(l));
    if (at === -1) out.push(line, `${propIndent}disabled: true`, ...body);
    else out.push(line, ...body.slice(0, at), `${propIndent}disabled: true`, ...body.slice(at + 1));
    changed += 1;
    i = j - 1;
  }
  for (const id of ids) {
    if (!seen.includes(id)) throw new Error(`row "${id}" is missing from the shipped preset`);
  }
  if (changed !== ids.length) throw new Error(`expected to change ${ids.length} row(s), changed ${changed}`);
  return out;
}

const presetRows = disableRows(unwrapShippedPreset(readFileSync(shippedPath, 'utf8')), [DISABLE]);

const HEADER = `# dsh-shell-getaway — loader patch.
#
# GENERATED by tools/build-bundle-patch.mjs — do not edit by hand.
# Regenerate:
#   node tools/build-bundle-patch.mjs <shipped-preset.patch.yml> bundle/cordis.patch.yml
# Verify:
#   node tools/assert-preset-override.mjs <shipped-preset.patch.yml> \\
#     <(sed -n '/^- id: preset-standard/,$p' bundle/cordis.patch.yml) tool-pwsh
#
# Applied LAST: the profile bundle list is
#   [@deepseek-ai/dsh-base, @deepseek-ai/dsh-web-app, @local/dsh-shell-getaway]
# so these rows override the shipped layers.
#
# ── 1. Host plane: stop the shipped pwsh TOOL ────────────────────────────────
#
# Why the preset override further down is not enough on its own (measured): after
# disabling \`tool-pwsh\` inside \`preset-standard\`, \`Tool.listTools\` STILL reported a
# \`pwsh\` tool. \`dsh-agent-preset-registry\` keeps an in-memory \`PresetTree\` whose
# \`write()\` is a no-op — its own comment says "only the profile configuration editor
# persists definitions" — so a bundle patch is not authoritative for a preset's
# plugin list. Disabling the host-plane row removes the other source.
#
# The standing rule for this plugin is that it must never silently degrade, and a
# second shell tool speaking the wrong dialect is exactly that: the model would write
# PowerShell into a bash executor, or the reverse, and only learn from the error.
# Both levers are therefore pulled, and whichever one bites is enough.
- id: ${DISABLE}
  name: '@deepseek-ai/dsh-tool-pwsh'
  disabled: true

# ── 2. The preset override, reproduced verbatim from the shipped preset ──────
#
# Only these rows differ from what the shipped file declares:
${[DISABLE].map((id) => `#   - ${id}: forced to \`disabled: true\``).join('\n')}
#
# ⚠️ A patch replaces the entire \`config\` and never deep-merges, so every other row
# below is a verbatim copy. Do not hand-edit: regenerate, then run the assertion.
`;

const FOOTER = `
# ── 3. Host plane: this plugin ───────────────────────────────────────────────
#
# One row. The plugin assigns \`ctx.shell\` first and then mounts the shipped
# \`@deepseek-ai/dsh-tool-bash\` inside one shared isolated scope, so the tool binds to
# THIS executor rather than to the host plane's PowerShell one — measured: mounting it
# on the root context produced a \`bash\` tool that ran PowerShell, because the tool
# captures \`ctx.shell\` when it activates.
- insert:
    - id: shell-getaway
      name: '@local/dsh-shell-getaway'
      config:
        shell: auto
        msysPathConv: off
`;

writeFileSync(outPath, `${HEADER}${presetRows.join('\n')}\n${FOOTER}`);
console.log(`wrote ${outPath}: ${presetRows.length} preset rows, ${DISABLE} disabled`);
